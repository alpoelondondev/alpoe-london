// Compiles every data/research/**/*.json model file into a single importable
// module (lib/generated/research-index.ts) so product pages can resolve verified
// specs/descriptions without reading the filesystem at request time.
import { readdirSync, readFileSync, existsSync, writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const RESEARCH_DIR = join(ROOT, "data", "research");
const OUT = join(ROOT, "lib", "generated", "research-index.ts");

function collect(dir) {
  const models = [];
  if (!existsSync(dir)) return models;
  for (const ent of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, ent.name);
    if (ent.isDirectory()) {
      models.push(...collect(full));
    } else if (ent.name.endsWith(".json")) {
      try {
        models.push(JSON.parse(readFileSync(full, "utf8")));
      } catch (err) {
        throw new Error(`Invalid research JSON: ${full}\n${err.message}`);
      }
    }
  }
  return models;
}

const models = collect(RESEARCH_DIR).sort((a, b) =>
  `${a.brandSlug}/${a.modelSlug}`.localeCompare(`${b.brandSlug}/${b.modelSlug}`),
);

const refCount = models.reduce((n, m) => n + Object.keys(m.references ?? {}).length, 0);

const body = `// AUTO-GENERATED by scripts/gen-research-index.mjs — do not edit by hand.
export type ReferenceResearch = {
  caseSize?: string;
  movement?: string;
  materials?: string;
  bezel?: string;
  dial?: string;
  waterResistance?: string;
  year?: string;
  description?: string;
  variants?: Record<string, string>;
};

export type ModelResearch = {
  brand: string;
  brandSlug: string;
  model: string;
  modelSlug: string;
  modelOverview?: string;
  references: Record<string, ReferenceResearch>;
};

export const RESEARCH: ModelResearch[] = ${JSON.stringify(models, null, 2)};
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, body, "utf8");
console.log(`research-index.ts written: ${models.length} models, ${refCount} references`);
