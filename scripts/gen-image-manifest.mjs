// Scans public/products/<brandSlug>/<reference>/ and writes a manifest mapping
// "<brandSlug>/<reference-lowercase>" -> ordered image paths under /public.
//
// Runs at build time (see the "prebuild" npm script) so the live sheet loader can
// resolve images by reference WITHOUT touching the filesystem at request time —
// public/ is not present in the serverless bundle on Vercel.
import { readdirSync, readFileSync, existsSync, writeFileSync, mkdirSync } from "node:fs";
import { createHash } from "node:crypto";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const PRODUCTS_DIR = join(ROOT, "public", "products");
const OUT = join(ROOT, "lib", "generated", "image-manifest.ts");
const VARIANTS_TSV = join(ROOT, "data", "variant-images.tsv");

const IMG_RE = /\.(png|jpe?g|webp|avif)$/i;

// Product images are served from the assets bucket (lib/assets.ts) with a
// year-long immutable cache header, so a re-exported 1.webp would otherwise be
// invisible to anyone who had seen the old one. Every path therefore carries a
// content hash as a query string — the bucket ignores it, the browser does not.
const version = (file) =>
  createHash("md5").update(readFileSync(file)).digest("hex").slice(0, 8);

// Must match referenceKey() in lib/catalogue.ts — folder names carry hyphenated
// references (Patek "5811/1G-001" -> "5811-1g-001"), and variants are folded the
// same way so "Wimbledon – Jubilee Fluted" keys as "wimbledon-jubilee-fluted".
const key = (s) =>
  s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");

function build() {
  const manifest = {};
  if (!existsSync(PRODUCTS_DIR)) return manifest;

  for (const brandSlug of readdirSync(PRODUCTS_DIR)) {
    const brandDir = join(PRODUCTS_DIR, brandSlug);
    let refs;
    try {
      refs = readdirSync(brandDir, { withFileTypes: true });
    } catch {
      continue; // not a directory
    }
    for (const ent of refs) {
      if (!ent.isDirectory()) continue;
      const ref = ent.name;
      const refDir = join(brandDir, ref);
      const images = readdirSync(refDir)
        .filter((f) => IMG_RE.test(f))
        .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }))
        .map((f) => `/products/${brandSlug}/${ref}/${f}?v=${version(join(refDir, f))}`);
      if (images.length) manifest[`${brandSlug}/${key(ref)}`] = images;
    }
  }
  return manifest;
}

// One Rolex reference covers many dial/bracelet configurations, and the sheet
// lists each as its own row. data/variant-images.tsv pins a specific file to a
// specific variant so those rows stop all showing image 1 of the reference.
function buildVariants(manifest) {
  const out = {};
  if (!existsSync(VARIANTS_TSV)) return out;

  const lines = readFileSync(VARIANTS_TSV, "utf8").split("\n");
  for (const [i, raw] of lines.entries()) {
    const line = raw.trim();
    if (!line || line.startsWith("#")) continue;
    const [brandSlug, reference, variant, file] = line
      .split("#")[0]
      .split("\t")
      .map((s) => (s ?? "").trim());
    if (!brandSlug || !reference || !variant || !file) {
      console.warn(`variant-images.tsv:${i + 1} malformed, skipped`);
      continue;
    }
    const refK = key(reference);
    const path = `/products/${brandSlug}/${refK}/${file}`;
    // A typo here would silently blank a product, so fail loudly instead.
    const versioned = (manifest[`${brandSlug}/${refK}`] ?? []).find(
      (p) => p.split("?")[0] === path,
    );
    if (!versioned) {
      console.warn(`variant-images.tsv:${i + 1} no such image: ${path}`);
      continue;
    }
    out[`${brandSlug}/${refK}/${key(variant)}`] = versioned;
  }
  return out;
}

const manifest = build();
const keys = Object.keys(manifest).sort();
const ordered = {};
for (const k of keys) ordered[k] = manifest[k];

const variants = buildVariants(manifest);
const vKeys = Object.keys(variants).sort();
const vOrdered = {};
for (const k of vKeys) vOrdered[k] = variants[k];

// data/products.csv names images by bare path; this lets it pick up the version.
const byPath = {};
for (const k of keys) for (const p of ordered[k]) byPath[p.split("?")[0]] = p;

const body = `// AUTO-GENERATED by scripts/gen-image-manifest.mjs — do not edit by hand.
// Maps "<brandSlug>/<reference-lowercase>" to ordered, content-versioned image
// paths under /public (served from the assets bucket in production — lib/assets.ts).
export const IMAGE_MANIFEST: Record<string, string[]> = ${JSON.stringify(ordered, null, 2)};

// Maps "<brandSlug>/<reference>/<variant>" to the one image for that configuration.
export const VARIANT_IMAGES: Record<string, string> = ${JSON.stringify(vOrdered, null, 2)};

// Maps a bare "/products/…/1.webp" path to its versioned form.
export const IMAGE_VERSIONS: Record<string, string> = ${JSON.stringify(byPath, null, 2)};
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, body, "utf8");
console.log(
  `image-manifest.ts written: ${keys.length} references with images, ${vKeys.length} variant pins`,
);
